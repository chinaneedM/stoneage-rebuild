"""PET72 source constraints: 2005 official pet names, Japanese sprite preloads, no global counts."""
import json,unittest
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
REC=ROOT/"research"/"recovered"
def read(n): return json.loads((REC/n).read_text(encoding="utf8"))
class PET72Evidence(unittest.TestCase):
 @classmethod
 def setUpClass(cls):
  cls.d=read("STONEAGE-PET72-YEAR2005-CN-TW-JP-KR-SOURCE-R1.json")
  cls.q=read("STONEAGE-PET27-GLOBAL-YEAR-VERSION-WORK-QUEUE-R1.json")
 def row(self,i): return next(x for x in self.d["source_records"] if x["id"]==i)
 def test_CN_75_names_skills_are_marketing_not_native_issuance(self):
  a=self.row("CN-2005-0412-WAEI-75-CHICKEN-OX")
  self.assertEqual(a["names"],["牛头人","鸡年兽"])
  self.assertEqual(a["skills_as_advertised"],["憾甲一击","肆无忌蛋"])
  self.assertEqual(a["applicable_server"],"CN_7_5_ONLY")
  self.assertFalse(a["native_skill_verified"])
  self.assertFalse(a["real_account_grants_verified"])
  self.assertTrue(a["operator_marketing_says_listed_but_also_tells_users_to_watch_for_upcoming_store_stock"] if "operator_marketing_says_listed_but_also_tells_users_to_watch_for_upcoming_store_stock" in a else "both claimed listed and later store availability to be watched" in a["evidence"])
  b=self.row("CN-2005-0412-WAEI-75-SECOND-REPRINT")
  self.assertFalse(b["is_second_operator_identity_evidence"])
 def test_TW_kirin_Laifu_rewards_not_actual_accounts(self):
  x=self.row("TW-2005-0126-KIRIN")
  self.assertEqual((x["names"],x["required_battle_points"],x["required_breeding_points"]),(["麒麟"],3500,60))
  self.assertFalse(x["reward_issued_to_real_account_verified"])
  y=self.row("TW-2005-0420-LAIFU")
  self.assertEqual(y["names"],["萊福"])
  self.assertEqual(y["advertised_skill"],"相棲共生")
  self.assertFalse(y["native_skill_formula_verified"])
  z=self.row("TW-2005-0608-EIGHT")
  self.assertEqual(z["reported_new_ride_pet_count_unnamed"],2)
  self.assertEqual(z["version"],"TW_8_0_失落的世界")
  self.assertEqual(z["original_2005_8_client_bytes_obtained"],0)
  w=self.row("TW-2005-0223-CHICKEN-RETROSPECTIVE")
  self.assertFalse(w["contemporaneous_original_2005_TW_article_acquired"])
  self.assertFalse(w["first_live_release_proven"])
  self.assertTrue(all("DIRECT_403" in a["grade"] for a in (x,y,z)))
 def test_JP_0705_sprite_preload_is_not_0705_LV1_live_pet(self):
  x=self.row("JP-2005-0705-0712-PATCH")
  self.assertEqual(x["first_patch_date"],"2005-07-05")
  self.assertEqual(x["second_patch_planned_date"],"2005-07-12")
  self.assertTrue(x["report_says_new_dinosaur_appears_after_second_patch"])
  self.assertIn("pet album extension",x["first_patch_content"])
  self.assertIn("previously absent level-one field dinosaurs",x["second_patch_content"])
  self.assertFalse(x["actual_server_application_verified"])
  self.assertEqual((x["first_original_patch_bytes_retrieved"],x["second_original_patch_bytes_retrieved"]),(0,0))
 def test_JP_names_and_naming_are_separate_not_confirmed_awards(self):
  a=self.row("JP-2005-0715-CROWURI")
  self.assertEqual(a["names"],["クロウリ"])
  self.assertFalse(a["actual_player_account_delivery_verified"])
  b=self.row("JP-2005-0722-UNNAMED-TIGER")
  self.assertIsNone(b["name_as_of_date"])
  self.assertFalse(b["same_identity_as_later_Vanrem_proven"])
  c=self.row("JP-2005-0921-GAVI")
  self.assertEqual(c["names"],["ガーヴィ"])
  self.assertEqual(c["promised_prize_count"],1)
  self.assertFalse(c["actual_winner_or_total_server_population_verified"])
  d=self.row("JP-2005-0930-VANREM")
  self.assertEqual(d["names"],["ヴァンレム"])
  self.assertFalse(d["same_as_july_unnamed_black_tiger_proven"])
  self.assertFalse(d["actual_customer_grant_verified"])
 def test_KR_ride_expansion_not_new_pet_birth(self):
  k=self.row("KR-2005-1011-TWO-RIDES")
  self.assertEqual(k["names"],["고르고르","타쿠"])
  self.assertEqual(k["reported_riding_options_after_update"],6)
  self.assertTrue(k["riding_options_not_newly_created_species"])
  self.assertTrue(k["additional_four_rides_by_november_are_future_promises"])
  self.assertFalse(k["original_pet_name_id_table_acquired"])
 def test_2005_year_is_open_all_regions_population_unknown(self):
  a,q=self.d,self.q
  self.assertEqual((a["active_module"],a["year"]),("PET",2005))
  self.assertEqual(len(a["source_records"]),12)
  self.assertEqual(q["current_frontier"]["year"],2005)
  self.assertGreaterEqual(int(q["current_frontier"]["latest_partial_root_review"].split("-")[0][3:]),72)
  self.assertRegex(q["current_frontier"]["next"],r"^PET[0-9]+:")
  y=next(z for z in q["yearly_work_queue"] if z["year"]==2005)
  self.assertEqual(y["research_gate"],"NOT_YEAR_AUDITED")
  self.assertEqual(y["documentary_event_count_NOT_species"],0)
  self.assertEqual(sum(x["id"]==a["id"] for x in y["partial_source_review_receipts"]),1)
  self.assertEqual(sum(x["id"]==a["id"] for x in q["root_source_census_receipts"]),1)
  self.assertEqual(q["yearly_work_queue"][5]["research_gate"],"SOURCE_BOUNDED_REVIEWED")
  self.assertFalse(q["yearly_work_queue"][5]["historically_complete"])
  self.assertEqual(set(a["region_scope"]),{"CN","TW","JP","KR","OTHER"})
  self.assertTrue(all(x["population"] is None for x in a["region_scope"].values()))
  self.assertIsNone(a["historical_2005_global_species_count"])
 def test_proprietary_rights_and_source_custody(self):
  a=self.d
  self.assertEqual((a["new_original_2005_client_bytes"],a["new_same_deployment_native_pet_ids"],a["new_verified_original_server_grant_logs"]),(0,0,0))
  self.assertTrue(a["no_paid_marketplace"])
  self.assertTrue(a["no_original_commercial_media_published"])
  self.assertTrue(a["historical_CURRENT_unchanged"])
  self.assertEqual(a["startup"]["historical_CURRENT_blob"],"c89e0e33537990aa2132b47c40fef49a985a935c")
  self.assertEqual((a["stage_A"],a["stage_B_wiki"],a["r79"]),("7_PARTIAL_2_OPEN","GATED","PAUSED_NON_BLOCKING"))
  self.assertIsNone(a["overall_percent"])
if __name__=="__main__":unittest.main()
